def gen_kinder_english(seed=0):
    random.seed(seed)
    P = []
    A = P.append
    VOC = [("кот", "cat"), ("собака", "dog"), ("солнце", "sun"), ("луна", "moon"), ("дом", "house"), ("мяч", "ball"),
           ("красный", "red"), ("синий", "blue"), ("зелёный", "green"), ("жёлтый", "yellow"),
           ("один", "one"), ("два", "two"), ("три", "three"), ("четыре", "four"), ("пять", "five"),
           ("мама", "mum"), ("папа", "dad"), ("молоко", "milk"), ("хлеб", "bread"), ("яблоко", "apple")]
    for i, (ru, en) in enumerate(VOC):
        q = [1, 2, 3, 4][i % 4]
        wrongs = [e for _, e in VOC if e != en]
        random.shuffle(wrongs)
        A(build_choice(f"Как по-английски «{ru}»?", en, wrongs[:3], f"«{ru}» — {en}.", "Words", [q]))
        wrongs2 = [r for r, _ in VOC if r != ru]
        random.shuffle(wrongs2)
        A(build_choice(f"Что означает слово «{en}»?", ru, wrongs2[:3], f"«{en}» — {ru}.", "Words", [q]))
    for _ in range(8):
        A(build_tf("Верно ли, что «cat» означает «кот»?", "Верно", "cat — кот.", "Words", [1, 2]))
        A(build_tf("Верно ли, что «sun» означает «луна»?", "Неверно", "sun — солнце, а луна — moon.", "Words", [3, 4]))
    return P


