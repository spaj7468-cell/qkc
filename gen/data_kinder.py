ALPH = "абвгдежзийклмнопрстуфхцчшщъыьэюя"


def gen_kinder_russian(seed=0):
    random.seed(seed)
    P = []
    A = P.append
    WORDS = [("кот", "к"), ("дом", "д"), ("мяч", "м"), ("сок", "с"), ("лес", "л"), ("мак", "м"), ("сыр", "с"),
             ("жук", "ж"), ("кит", "к"), ("борщ", "б"), ("арбуз", "а"), ("утка", "у"), ("игла", "и"), ("оса", "о"),
             ("эхо", "э")]
    for w, l in WORDS:
        q = random.choice([[1, 2], [3, 4]])
        others = [x for x in ALPH if x != l]
        random.shuffle(others)
        A(build_choice(f"С какой буквы начинается слово «{w}»?", l, others[:3],
                       f"Слово «{w}» начинается с буквы «{l}».", "Буквы", q))
    VOW = list("аеёиоуыэюя")
    for _ in range(14):
        v = random.choice(VOW)
        wrong = [c for c in "бвгджзклмнпрстфхцчшщ" ][:3]
        A(build_choice(f"Какая из этих букв гласная?", v, wrong,
                       f"«{v}» — гласная: её можно пропеть.", "Гласные и согласные", [1, 2]))
    for _ in range(14):
        c = random.choice(list("бвгдкмнпрстф"))
        wrong = [x for x in VOW][:3]
        A(build_choice(f"Какая из этих букв согласная?", c, wrong,
                       f"«{c}» — согласная: при произнесении встречает преграду.", "Гласные и согласные", [1, 2]))
    for w in ["мама", "папа", "каша", "луна", "дым", "кот", "рука", "нога", "молоко", "собака"]:
        n = len([c for c in w if c in "аеёиоуыэюя"])
        A(build_choice(f"Сколько слогов в слове «{w}»?", n, [x for x in (n + 1, n - 1, n + 2, 1) if x > 0 and x != n][:3],
                       f"Слогов столько, сколько гласных: {n}.", "Слоги", [3, 4]))
    for i in range(0, len(ALPH) - 2, 3):
        w = [ALPH[i + 1], ALPH[i + 2], ALPH[i - 1] if i > 0 else ALPH[i + 3], ALPH[(i + 4) % len(ALPH)]]
        w = [x for x in dict.fromkeys(w) if x != ALPH[i + 1]][:3]
        A(build_choice(f"Какая буква идёт после «{ALPH[i]}»?", ALPH[i + 1], w,
                       f"Алфавит: …{ALPH[i]}{ALPH[i+1]}…", "Алфавит", [1, 2]))
    for w, l in WORDS[:10]:
        A(build_choice(f"С какого звука начинается слово «{w}»?", f"со звука [{l}]", [f"со звука [{l}]", "со звука [а]",
                       f"со звука [{w[-1]}]", "со звука [о]"], f"Первый звук слова «{w}» — [{l}].", "Звуки", [3, 4]))
    A(build_choice("Сколько букв в русском алфавите?", "33", ["33", "30", "26", "32"], "В русском алфавите 33 буквы.", "Алфавит", [1, 2]))
    A(build_tf("Буква «ь» не обозначает звука.", "Верно", "Мягкий знак звука не имеет.", "Буквы", [3, 4]))
    A(build_tf("Слово «кот» состоит из трёх букв.", "Верно", "К, о, т — три буквы.", "Буквы", [1, 2]))
    return P


