def econ_tasks(q):
    """Расчётные задачи по экономике."""
    out = []
    for _ in range(6):
        inc = random.choice([10000, 20000, 30000, 50000, 80000])
        ndfl = inc * 13 // 100
        out.append(build_input(f"Заработная плата {inc} руб., НДФЛ 13%. Сколько рублей составит налог?", ndfl,
                               f"{inc} · 0,13 = {ndfl} руб.", "Налоги", q))
        out.append(build_input(f"Заработная плата {inc} руб., НДФЛ 13%. Сколько рублей работник получит «на руки»?", inc - ndfl,
                               f"{inc} − {ndfl} = {inc - ndfl} руб.", "Налоги", q))
    for _ in range(6):
        price = random.choice([200, 500, 1000, 2000, 5000])
        vat = price * 20 // 100
        out.append(build_input(f"Цена товара без НДС {price} руб., ставка НДС 20%. Чему равен НДС (руб.)?", vat,
                               f"{price} · 0,20 = {vat} руб.", "Налоги", q))
    for _ in range(6):
        cost = random.choice([200, 400, 500, 1000, 2500])
        markup = random.choice([10, 20, 25, 50])
        out.append(build_input(f"Себестоимость товара {cost} руб., наценка {markup}%. Какова цена продажи (руб.)?",
                               cost + cost * markup // 100, f"{cost} + {cost}·{markup}/100 = {cost + cost*markup//100} руб.", "Прибыль и цена", q))
        out.append(build_input(f"Себестоимость товара {cost} руб., цена продажи {cost + cost*markup//100} руб. Какова прибыль с одной единицы (руб.)?",
                               cost * markup // 100, f"Прибыль = цена − себестоимость = {cost*markup//100} руб.", "Прибыль и цена", q))
    for _ in range(6):
        q1 = random.choice([50, 100, 200, 500]); p1 = random.choice([10, 20, 50, 100])
        out.append(build_input(f"Выручка от продажи {q1} единиц товара по {p1} руб. равна … (руб.)", q1 * p1,
                               f"Выручка = цена · количество = {p1}·{q1} = {q1*p1} руб.", "Выручка", q))
    for _ in range(5):
        infl = random.choice([50, 100, 200])
        out.append(build_input(f"Индекс цен вырос на {infl - 100}% (стал {infl}% от прежнего). Товар стоил 1000 руб. Какова его новая цена (руб.)?",
                               1000 * infl // 100, f"1000 · {infl}/100 = {1000*infl//100} руб.", "Инфляция", q))
    for _ in range(5):
        s = random.choice([100000, 200000, 500000]); r = random.choice([8, 10, 12, 15])
        out.append(build_input(f"Вклад {s} руб. под {r}% годовых. Сколько рублей процентов начислят за год?", s * r // 100,
                               f"{s} · {r}/100 = {s*r//100} руб.", "Банк и кредит", q))
    for _ in range(5):
        n = random.choice([3, 4, 5]); h = random.choice([2, 3, 4])
        out.append(build_input(f"Рабочий изготавливает {n} детали в час. Сколько деталей он сделает за {h} ч?", n * h,
                               f"Производительность × время = {n}·{h} = {n*h}.", "Производительность труда", q))
    for _ in range(5):
        inc = random.choice([30000, 50000, 80000, 120000]); exp = random.choice([10000, 20000, 30000, 40000])
        while exp > inc:
            exp -= 5000
        out.append(build_input(f"Доход семьи {inc} руб., расходы {exp} руб. Каковы сбережения (руб.)?", inc - exp,
                               f"Сбережения = доходы − расходы = {inc} − {exp} = {inc-exp} руб.", "Семейный бюджет", q))
    return out


