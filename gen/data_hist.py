def gen_hist(grade, seed=0):
    random.seed(seed)
    P = []
    A = P.append
    d = H[grade]
    P.extend(pairs_items(d["ev"], "В каком году (периоде) произошло событие «{a}»?", "Какое событие произошло: {b}?",
                          "Даты и события", [1, 2], tfmt="событие «{a}» относится к {b}"))
    P.extend(pairs_items(d["pe"], "Кто такой {a}?", "О ком идёт речь: «{b}»?", "Исторические личности", [3, 4],
                          tfmt="{a} — это {b}"))
    P.extend(pairs_items(d["te"], "Что означает термин «{a}»?", "Определение «{b}» относится к термину:",
                          "Исторические термины", [1, 2], tfmt="{a} — {b}"))
    # хронологические задачи
    years = []
    for ev, dt in d["ev"]:
        m = "".join(ch for ch in dt if ch.isdigit())
        if len(m) >= 4:
            years.append((ev, int(m[:4]), "до н. э." in dt))
    if len(years) >= 4:
        for _ in range(6):
            e, y, bc = random.choice(years)
            others = [x[0] for x in years if x[0] != e]
            random.shuffle(others)
            A(build_choice(f"Какое из событий произошло в {y} году{' до н. э.' if bc else ''}?", e, others[:3],
                           f"Событие «{e}» датируется {y} годом{' до н. э.' if bc else ''}.", "Хронология", [3, 4]))
        for _ in range(6):
            a1, a2 = random.sample(years, 2)
            if a1[2] or a2[2]:
                continue
            earlier = a1 if a1[1] < a2[1] else a2
            later = a2 if earlier is a1 else a1
            A(build_choice(f"Какое событие произошло раньше?", earlier[0], [earlier[0], later[0],
                           random.choice([x[0] for x in years if x not in (a1, a2)])],
                           f"{earlier[0]} — {earlier[1]} г., {later[0]} — {later[1]} г.", "Хронология", [3, 4]))
    A(build_choice("Сколько десятилетий в одном веке?", "10", ["10", "100", "5", "50"], "Век = 100 лет = 10 десятилетий.", "Хронология", [1, 2]))
    A(build_choice("Какой век следует за XVIII веком?", "XIX век", ["XIX век", "XX век", "XVII век", "XXI век"], "18 → 19.", "Хронология", [1, 2]))
    A(build_choice("1945 год — это …", "XX век", ["XX век", "XIX век", "XXI век", "XVIII век"], "1901–2000 гг. — XX век.", "Хронология", [1, 2]))
    A(build_tf("Исторический источник — это всё, что несёт информацию о прошлом.", "Верно",
               "Летописи, предметы, здания, монеты — всё это источники.", "Историческая наука", [1, 2]))
    A(build_choice("Наука, изучающая рукописные тексты:", "палеография", ["палеография", "археология", "нумизматика", "этнография"],
                   "Палеография изучает древнее письмо.", "Историческая наука", [3, 4]))
    A(build_choice("Наука о монетах:", "нумизматика", ["нумизматика", "геральдика", "археология", "хронология"], "Нумизматика изучает монеты.", "Историческая наука", [3, 4]))
    A(build_choice("Наука о гербах:", "геральдика", ["геральдика", "нумизматика", "топонимика", "эпиграфика"], "Геральдика изучает гербы.", "Историческая наука", [3, 4]))
    return P
